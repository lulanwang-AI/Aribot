export const ORGANISMS_BY_ID: Record<string, Organism> = Object.fromEntries(
  ORGANISMS.map((o) => [o.id, o]),
);

export function getOrganism(id: string): Organism {
  const organism = ORGANISMS_BY_ID[id];
  if (!organism) throw new Error(`Unknown organism id: ${id}`);
  return organism;
}
